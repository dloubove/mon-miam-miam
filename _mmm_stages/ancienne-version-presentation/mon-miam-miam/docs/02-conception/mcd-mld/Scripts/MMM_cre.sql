-- Structure PostgreSQL de Mon Miam Miam (22 tables, version 2.0).
SET search_path TO mmm, public;

CREATE DOMAIN id_entite AS integer CHECK (VALUE > 0);
CREATE DOMAIN nom_long AS varchar(150) CHECK (length(trim(VALUE)) > 0);
CREATE DOMAIN email AS varchar(150) CHECK (VALUE SIMILAR TO '%@%.%');
CREATE DOMAIN telephone AS varchar(20) CHECK (VALUE SIMILAR TO '[0-9+() -]{7,20}');
CREATE DOMAIN montant_fcfa AS numeric(10,0) CHECK (VALUE >= 0);
CREATE DOMAIN quantite AS integer CHECK (VALUE > 0);
CREATE DOMAIN points AS integer;
CREATE DOMAIN date_op AS date CHECK (VALUE >= DATE '2020-01-01');
CREATE DOMAIN horodatage AS timestamp CHECK (VALUE >= TIMESTAMP '2020-01-01 00:00:00');
CREATE DOMAIN statut_compte AS varchar(10) CHECK (VALUE IN ('actif','inactif'));
CREATE DOMAIN libelle_role AS varchar(30) CHECK (VALUE IN ('employe','gerant','administrateur'));
CREATE DOMAIN mode_service AS varchar(15) CHECK (VALUE IN ('sur_place','livraison'));
CREATE DOMAIN statut_commande AS varchar(20) CHECK (VALUE IN ('panier','en_attente','en_preparation','prete','servie','livree','annulee'));
CREATE DOMAIN mode_paiement AS varchar(20) CHECK (VALUE IN ('carte','mobile_money','points','especes'));
CREATE DOMAIN statut_paiement AS varchar(20) CHECK (VALUE IN ('en_attente','reussi','echoue','rembourse'));
CREATE DOMAIN type_mouvement AS varchar(30) CHECK (VALUE IN ('gain_commande','gain_parrainage','gain_evenement','gain_mini_jeu','utilisation','expiration','ajustement'));
CREATE DOMAIN statut_reclamation AS varchar(20) CHECK (VALUE IN ('ouverte','repondue','validee','rejetee'));
CREATE DOMAIN decision AS varchar(10) CHECK (VALUE IN ('validee','rejetee'));
CREATE DOMAIN type_evenement AS varchar(20) CHECK (VALUE IN ('evenement','mini_jeu'));
CREATE DOMAIN statut_mini_jeu AS varchar(10) CHECK (VALUE IN ('actif','inactif'));

CREATE TABLE utilisateur (
 id_utilisateur integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_utilisateur > 0),
 nom nom_long NOT NULL, email email NOT NULL UNIQUE, mot_de_passe varchar(255) NOT NULL,
 telephone telephone NOT NULL, date_inscription horodatage NOT NULL DEFAULT current_timestamp,
 statut_compte statut_compte NOT NULL DEFAULT 'actif'
);
CREATE TABLE etudiant (
 id_utilisateur integer PRIMARY KEY REFERENCES utilisateur ON DELETE RESTRICT,
 code_parrainage varchar(20) NOT NULL UNIQUE, solde_points points NOT NULL DEFAULT 0 CHECK (solde_points >= 0),
 localisation varchar(255), id_parrain integer REFERENCES etudiant(id_utilisateur) ON DELETE RESTRICT,
 date_parrainage horodatage, recompense_attribuee boolean NOT NULL DEFAULT false,
 points_parrainage points CHECK (points_parrainage >= 0),
 CHECK (id_parrain IS NULL OR id_parrain <> id_utilisateur),
 CHECK ((id_parrain IS NULL) = (date_parrainage IS NULL))
);
CREATE TABLE personnel (
 id_utilisateur integer PRIMARY KEY REFERENCES utilisateur ON DELETE RESTRICT,
 matricule varchar(20) NOT NULL UNIQUE, date_embauche date NOT NULL,
 id_role integer NOT NULL, id_restaurant integer, id_createur integer REFERENCES personnel(id_utilisateur) ON DELETE RESTRICT,
 date_creation_compte horodatage NOT NULL DEFAULT current_timestamp
);
CREATE TABLE role (
 id_role integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_role > 0),
 libelle_role libelle_role NOT NULL UNIQUE
);
CREATE TABLE restaurant (
 id_restaurant integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_restaurant > 0),
 nom_restaurant nom_long NOT NULL, adresse_restaurant varchar(255) NOT NULL,
 telephone_restaurant telephone NOT NULL
);
ALTER TABLE personnel ADD CONSTRAINT fk_personnel_role FOREIGN KEY (id_role) REFERENCES role ON DELETE RESTRICT;
ALTER TABLE personnel ADD CONSTRAINT fk_personnel_restaurant FOREIGN KEY (id_restaurant) REFERENCES restaurant ON DELETE RESTRICT;
CREATE TABLE parametre (
 id_parametre integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_parametre > 0),
 cle_parametre varchar(60) NOT NULL, valeur_parametre varchar(255) NOT NULL,
 description_parametre varchar(255), id_restaurant integer NOT NULL REFERENCES restaurant ON DELETE RESTRICT,
 UNIQUE (id_restaurant, cle_parametre)
);
CREATE TABLE categorie (
 id_categorie integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_categorie > 0),
 libelle_categorie nom_long NOT NULL UNIQUE
);
CREATE TABLE article (
 id_article integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_article > 0),
 nom_article nom_long NOT NULL, description_article text, prix_unitaire numeric(10,0) NOT NULL CHECK (prix_unitaire > 0),
 image_article varchar(255), disponible boolean NOT NULL DEFAULT true,
 id_categorie integer NOT NULL REFERENCES categorie ON DELETE RESTRICT,
 id_restaurant integer NOT NULL REFERENCES restaurant ON DELETE RESTRICT
);
CREATE TABLE menu_jour (
 id_menu_jour integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_menu_jour > 0),
 date_menu date NOT NULL, id_restaurant integer NOT NULL REFERENCES restaurant ON DELETE RESTRICT,
 UNIQUE (id_restaurant, date_menu)
);
CREATE TABLE composer (
 id_menu_jour integer NOT NULL REFERENCES menu_jour ON DELETE CASCADE,
 id_article integer NOT NULL REFERENCES article ON DELETE CASCADE,
 PRIMARY KEY (id_menu_jour, id_article)
);
CREATE TABLE promotion (
 id_promotion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_promotion > 0),
 titre_promotion nom_long NOT NULL, description_promotion text,
 taux_reduction numeric(5,2) NOT NULL CHECK (taux_reduction BETWEEN 0 AND 100),
 date_debut_promo date_op NOT NULL, date_fin_promo date_op NOT NULL,
 affiche_promo varchar(255), CHECK (date_fin_promo >= date_debut_promo)
);
CREATE TABLE commande (
 id_commande integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_commande > 0),
 date_commande horodatage NOT NULL DEFAULT current_timestamp, statut_commande statut_commande NOT NULL DEFAULT 'panier',
 mode_service mode_service NOT NULL, heure_arrivee time, adresse_livraison varchar(255),
 montant_total montant_fcfa NOT NULL DEFAULT 0, points_utilises points NOT NULL DEFAULT 0 CHECK(points_utilises >= 0),
 reduction_points montant_fcfa NOT NULL DEFAULT 0, points_gagnes points NOT NULL DEFAULT 0 CHECK(points_gagnes >= 0),
 commentaire_client text, date_commentaire horodatage, date_validation horodatage,
 id_etudiant integer NOT NULL REFERENCES etudiant ON DELETE RESTRICT,
 id_restaurant integer NOT NULL REFERENCES restaurant ON DELETE RESTRICT,
 id_validateur integer REFERENCES personnel(id_utilisateur) ON DELETE RESTRICT,
 id_promotion integer REFERENCES promotion ON DELETE RESTRICT,
 CHECK ((mode_service = 'sur_place' AND heure_arrivee IS NOT NULL) OR (mode_service = 'livraison' AND adresse_livraison IS NOT NULL))
);
CREATE TABLE contenir (
 id_commande integer NOT NULL REFERENCES commande ON DELETE CASCADE,
 id_article integer NOT NULL REFERENCES article ON DELETE RESTRICT,
 quantite quantite NOT NULL, prix_applique numeric(10,0) NOT NULL CHECK (prix_applique > 0),
 PRIMARY KEY (id_commande, id_article)
);
CREATE TABLE paiement (
 id_paiement integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_paiement > 0),
 montant_paye numeric(10,0) NOT NULL CHECK (montant_paye > 0), mode_paiement mode_paiement NOT NULL,
 reference_transaction varchar(100), statut_paiement statut_paiement NOT NULL DEFAULT 'en_attente',
 date_paiement horodatage NOT NULL DEFAULT current_timestamp,
 id_commande integer NOT NULL REFERENCES commande ON DELETE RESTRICT
);
CREATE TABLE mouvement_points (
 id_mouvement integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_mouvement > 0),
 type_mouvement type_mouvement NOT NULL, nombre_points points NOT NULL CHECK (nombre_points <> 0),
 date_mouvement horodatage NOT NULL DEFAULT current_timestamp, date_expiration_points date_op,
 id_etudiant integer NOT NULL REFERENCES etudiant ON DELETE RESTRICT,
 id_commande integer REFERENCES commande ON DELETE RESTRICT,
 CHECK ((type_mouvement NOT IN ('gain_commande','gain_parrainage','gain_evenement','gain_mini_jeu') OR nombre_points > 0)
    AND (type_mouvement NOT IN ('utilisation','expiration') OR nombre_points < 0)
    AND (type_mouvement NOT IN ('gain_commande','utilisation') OR id_commande IS NOT NULL))
);
CREATE TABLE reclamation (
 id_reclamation integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_reclamation > 0),
 objet nom_long NOT NULL, description_reclamation text NOT NULL,
 date_reclamation horodatage NOT NULL DEFAULT current_timestamp,
 statut_reclamation statut_reclamation NOT NULL DEFAULT 'ouverte',
 id_etudiant integer NOT NULL REFERENCES etudiant ON DELETE RESTRICT,
 id_commande integer REFERENCES commande ON DELETE RESTRICT,
 reponse_proposee text, date_reponse horodatage,
 id_repondant integer REFERENCES personnel(id_utilisateur) ON DELETE RESTRICT,
 decision_gerant decision, motif_decision text, date_decision horodatage,
 id_decideur integer REFERENCES personnel(id_utilisateur) ON DELETE RESTRICT,
 CHECK (decision_gerant IS NULL OR (reponse_proposee IS NOT NULL AND date_reponse IS NOT NULL AND date_decision IS NOT NULL AND date_decision >= date_reponse))
);
CREATE TABLE evenement (
 id_evenement integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_evenement > 0),
 titre_evenement nom_long NOT NULL, type_evenement type_evenement NOT NULL DEFAULT 'evenement',
 description_evenement text, date_debut_evenement horodatage NOT NULL, date_fin_evenement horodatage NOT NULL,
 points_recompense points NOT NULL DEFAULT 0 CHECK (points_recompense >= 0), affiche_evenement varchar(255),
 CHECK (date_fin_evenement >= date_debut_evenement)
);
CREATE TABLE participer (
 id_etudiant integer NOT NULL REFERENCES etudiant ON DELETE RESTRICT,
 id_evenement integer NOT NULL REFERENCES evenement ON DELETE RESTRICT,
 date_participation horodatage NOT NULL DEFAULT current_timestamp,
 score points CHECK (score >= 0), points_gagnes points NOT NULL DEFAULT 0 CHECK (points_gagnes >= 0),
 PRIMARY KEY (id_etudiant, id_evenement)
);
CREATE TABLE mini_jeu (
 id_mini_jeu integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_mini_jeu > 0),
 nom_mini_jeu nom_long NOT NULL UNIQUE, description_mini_jeu text,
 points_maximum points NOT NULL CHECK (points_maximum > 0), statut_mini_jeu statut_mini_jeu NOT NULL DEFAULT 'actif',
 affiche_mini_jeu varchar(255)
);
CREATE TABLE jouer (
 id_etudiant integer NOT NULL REFERENCES etudiant ON DELETE RESTRICT,
 id_mini_jeu integer NOT NULL REFERENCES mini_jeu ON DELETE RESTRICT,
 date_partie horodatage NOT NULL DEFAULT current_timestamp,
 score_partie points NOT NULL CHECK (score_partie >= 0), points_remportes points NOT NULL DEFAULT 0 CHECK (points_remportes >= 0),
 PRIMARY KEY (id_etudiant, id_mini_jeu, date_partie)
);
CREATE TABLE jeton_mdp (
 id_jeton integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_jeton > 0),
 jeton_hash varchar(255) NOT NULL UNIQUE, date_expiration_jeton horodatage NOT NULL,
 jeton_utilise boolean NOT NULL DEFAULT false,
 id_utilisateur integer NOT NULL REFERENCES utilisateur ON DELETE RESTRICT
);
CREATE TABLE consentement (
 id_consentement integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id_consentement > 0),
 finalite varchar(50) NOT NULL, consentement_accorde boolean NOT NULL,
 date_consentement horodatage NOT NULL DEFAULT current_timestamp,
 id_utilisateur integer NOT NULL REFERENCES utilisateur ON DELETE RESTRICT
);

CREATE INDEX ix_commande_etudiant_date ON commande(id_etudiant, date_commande);
CREATE INDEX ix_commande_restaurant_date ON commande(id_restaurant, date_commande);
CREATE INDEX ix_paiement_commande ON paiement(id_commande);
CREATE INDEX ix_mouvement_etudiant_date ON mouvement_points(id_etudiant, date_mouvement);
-- Un seul crédit de fidélité par commande et une seule consommation de points par commande.
CREATE UNIQUE INDEX uq_mouvement_gain_commande ON mouvement_points(id_commande)
 WHERE type_mouvement='gain_commande' AND id_commande IS NOT NULL;
CREATE UNIQUE INDEX uq_mouvement_utilisation_commande ON mouvement_points(id_commande)
 WHERE type_mouvement='utilisation' AND id_commande IS NOT NULL;
